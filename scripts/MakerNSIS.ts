		'  !undef MUI_FINISHPAGE_TEXT',
		'!endif',
		'!ifdef MUI_FINISHPAGE_TITLE_3LINES',
		'  !undef MUI_FINISHPAGE_TITLE_3LINES',
		'!endif',
		'!define MUI_FINISHPAGE_TITLE "${WOK_NAME} was removed"',
