/*
 * Refresh tests/fixtures/krunker-css-inventory.json from the live game stylesheets.
 *
 * assets/theme-game.css restyles Krunker's own UI, which means it names hundreds of class and id
 * hooks this project does not own. Guessing those names produces CSS that silently does nothing,
 * so the names are taken from the shipped stylesheets and committed as a fixture that
 * tests/themes.test.ts checks the theme layer against. When Krunker renames a hook, refreshing
 * this fixture turns the rename into a failing test instead of a dead rule nobody notices.
 *
 * Usage: node scripts/fetch-krunker-css-inventory.mjs
 *
 * Network access is deliberately confined to this script. The test reads only the fixture, so the
 * suite stays offline and deterministic.
 */

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Every stylesheet krunker.io links from its document head that carries UI hooks. flag.css and
 * google-play.css are omitted: they only define country flag sprites and a store badge, neither of
 * which a theme has anything to say about.
 */
const SOURCES = [
	'https://krunker.io/css/main.css',
	'https://krunker.io/css/bundledStyles.css',
	'https://krunker.io/css/main_custom.css',
	'https://krunker.io/css/material-icons.css',
	'https://krunker.io/css/material-icons-outlined.css',
	'https://krunker.io/css/material-symbols-outlined.css'
];

const OUTPUT = join(import.meta.dirname, '..', 'tests', 'fixtures', 'krunker-css-inventory.json');

/** Drop comments and the bodies of at-rules so only real selectors are scanned. */
function selectorsOf(css) {
	const withoutComments = css.replaceAll(/\/\*[\s\S]*?\*\//gu, '');
	return [...withoutComments.matchAll(/(^|\}|\{)([^{}]+)\{/gu)]
		.map(match => match[2].trim().replace(/\s+/gu, ' '))
		.filter(selector => selector.length > 0 && !selector.startsWith('@'));
}

async function main() {
	const ids = new Set();
	const classes = new Set();
	const customProperties = new Set();
	const sources = [];

	for (const url of SOURCES) {
		const response = await fetch(url);
		if (!response.ok) throw new Error(`${url} responded ${response.status}`);
		const css = await response.text();

		const selectors = selectorsOf(css);
		for (const selector of selectors) {
			for (const match of selector.matchAll(/#([A-Za-z][\w-]*)/gu)) ids.add(match[1]);
			for (const match of selector.matchAll(/\.([A-Za-z][\w-]*)/gu)) classes.add(match[1]);
		}
		for (const match of css.matchAll(/(--[a-z][a-z0-9-]*)\s*:/gu)) customProperties.add(match[1]);

		sources.push({
			bytes: Buffer.byteLength(css),
			rules: selectors.length,
			sha256: createHash('sha256').update(css).digest('hex'),
			url
		});
	}

	const inventory = {
		classes: [...classes].sort(),
		customProperties: [...customProperties].sort(),
		fetchedAt: new Date().toISOString().slice(0, 10),
		ids: [...ids].sort(),
		note: 'Generated by scripts/fetch-krunker-css-inventory.mjs. Do not hand-edit.',
		sources
	};

	writeFileSync(OUTPUT, `${JSON.stringify(inventory, null, '\t')}\n`);
	console.log(`Wrote ${OUTPUT}: ${inventory.ids.length} ids, ${inventory.classes.length} classes, ${inventory.customProperties.length} custom properties.`);
}

await main();
