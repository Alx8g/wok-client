function resolveIcon(iconPath: string | undefined): string | undefined {
	if (!iconPath) return undefined;
	const absolute = path.isAbsolute(iconPath) ? iconPath : path.resolve(process.cwd(), iconPath);
	const withIcoExt = path.extname(absolute).toLowerCase() === '.ico' ? absolute : `${absolute.replace(/\.[^/.]+$/, '')}.ico`;
	try {
		fs.accessSync(withIcoExt);
		return withIcoExt;
	} catch {
		return undefined;
	}
}
function resolveInstallerArt():
	| {
			header: string;
			side: string;
	  }
	| undefined {
	const header = path.join(INSTALLER_ART_DIR, INSTALLER_ART_FILES.header);
	const side = path.join(INSTALLER_ART_DIR, INSTALLER_ART_FILES.side);
	if (fs.existsSync(header) && fs.existsSync(side)) return { header, side };
	try {
		writeInstallerArt();
		return { header, side };
	} catch (error) {
		console.warn(`Building the installer without branding bitmaps: ${(error as Error).message}`);
		return undefined;
	}
}
function nsisText(value: string): string {
	return value
		.replace(/[\r\n]+/g, ' ')
		.replace(/\$/g, '$$$$')
		.replace(/"/g, '$\\"')
		.trim();
}
